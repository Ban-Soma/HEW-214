void Geometory::MakeBox()
{
	//--- 頂点の作成
	Vertex vtx[] = {
		//-Z面
		{{-0.5f,0.5f,-0.5f},{0.0f,0.0f}}, //0
		{{0.5f,0.5f,-0.5f},{1.0f,0.0f}}, //1
		{{-0.5f,-0.5f,-0.5f},{0.0f,1.0f}}, //2
		{{0.5f,-0.5f,-0.5f},{1.0f,1.0f}}, //3
		//+X面
		{{0.5f,0.5f,-0.5f},{0.0f,0.0f}}, //4
		{{0.5f,0.5f,0.5f},{1.0f,0.0f}}, //5
		{{0.5f,-0.5f,-0.5f},{0.0f,1.0f}}, //6
		{{0.5f,-0.5f,0.5f},{1.0f,1.0f}}, //7
		//+Z面
		{{0.5f,0.5f,0.5f},{0.0f,0.0f}}, //8
		{{-0.5f,0.5f,0.5f},{1.0f,0.0f}}, //9
		{{0.5f,-0.5f,0.5f},{0.0f,1.0f}}, //10
		{{-0.5f,-0.5f,0.5f},{1.0f,1.0f}}, //11
		//-X面
		{{-0.5f,0.5f,-0.5f},{1.0f,0.0f}}, //12
		{{-0.5f,0.5f,0.5f},{0.0f,0.0f}}, //13
		{{-0.5f,-0.5f,-0.5f},{1.0f,1.0f}}, //14
		{{-0.5f,-0.5f,0.5f},{0.0f,1.0f}}, //15
		//+Y面
		{{-0.5f,0.5f,0.5f},{0.0f,0.0f}}, //16
		{{0.5f,0.5f,0.5f},{1.0f,0.0f}}, //17
		{{-0.5f,0.5f,-0.5f},{0.0f,1.0f}}, //18
		{{0.5f,0.5f,-0.5f},{1.0f,1.0f}}, //19
		//-Y面
		{{-0.5f,-0.5f,0.5f},{1.0f,0.0f}}, //20
		{{0.5f,-0.5f,0.5f},{0.0f,0.0f}}, //21
		{{-0.5f,-0.5f,-0.5f},{1.0f,1.0f}}, //22
		{{0.5f,-0.5f,-0.5f},{0.0f,1.0f}}, //23
	};

	//--- インデックスの作成
	int idx[] = {
		0,1,2,1,3,2, //-Z面
		4,5,6,5,7,6, //+X面
		8,9,11,8,11,10,//+Z面
		14,13,12,15,13,14,//-X面
		16,17,18,17,19,18,//+Y面
		21,20,22,21,22,23,//-Y面
	};
	// バッファの作成
	MeshBuffer::Description desc = {};
	desc.pVtx = vtx;//頂点データ
	desc.vtxCount = _countof(vtx);//頂点の数
	desc.vtxSize = sizeof(Vertex);//頂点一つ当たりのデータサイズ
	desc.pIdx = idx; //インデックスのデータ
	desc.idxCount = _countof(idx);//インデックスの数
	desc.idxSize = sizeof(int);//インデックス一つ当たりのデータサイズ
	desc.topology = D3D11_PRIMITIVE_TOPOLOGY_TRIANGLELIST;

	m_pBox = new MeshBuffer();
	m_pBox->Create(desc);
}

